import Ajv from 'ajv';
import standaloneCode from 'ajv/dist/standalone';
import {runAsEntryPoint, type SectionValidatorsFileIo} from './sectionValidatorsFile.ts';
import schema0 from '../src/save/infrastructure/wireFormat/schemas/section0-player-progression.schema.json' with {type: 'json'};
import schema1 from '../src/save/infrastructure/wireFormat/schemas/section1-terraformation-levels.schema.json' with {type: 'json'};
